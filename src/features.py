# -*- coding: utf-8 -*-
"""
features.py  ——  从诗句里抽“特征”：意象词频、季节词频

【为什么不用 jieba 分词】
古诗和现代汉语是两种语言。jieba 的词典是新闻语料训出来的，切“床前明月光”会得到
“床前/明月/光”——“月”这个最核心的意象反而被并进“明月”里丢掉了。
而古诗的意象本来就是“单字成词”：月、酒、山、剑、秋。
所以这里改用最朴素也最可靠的办法：**意象词表 + 字符串计数**。
好处是可解释、可复现、零依赖，而且准确率比分词更高。

【为什么在繁体原文上统计】
“雲”和“云”在简体里合并成了一个字，但古文里“云”还常作“说”解（“诗云”）。
如果先转简体再统计，“云”的频次会被“说”污染。因此意象计数跑在繁体原文上，
词表里同时收录异体字（如 峰/峯、溪/谿、雁/鴈）。
"""

import re

import pandas as pd

# ---------------------------------------------------------------------------
# 意象词表：键是简体名（用于展示），值是繁体原文中可能出现的写法
# ---------------------------------------------------------------------------
IMAGERY = {
    "月": ["月", "蟾"],
    "酒": ["酒", "觴", "盃", "杯", "醉"],
    "山": ["山", "峰", "峯", "嶺", "岭"],
    "水": ["水", "江", "河", "溪", "谿"],
    "云": ["雲"],                       # 只数“雲”，避开作“说”解的“云”
    "风": ["風"],
    "花": ["花", "蕊"],
    "秋": ["秋", "霜", "雁", "鴈"],
    "雨": ["雨", "露"],
    "剑": ["劍", "戈", "刀"],
}

# 四季词表：用来观察“季节意象”的分布
SEASON = {
    "春": ["春", "花", "柳", "鶯", "燕"],
    "夏": ["夏", "荷", "蓮", "蟬", "暑"],
    "秋": ["秋", "霜", "雁", "鴈", "菊"],
    "冬": ["冬", "雪", "梅", "寒", "冰"],
}


def _count_words(series, words):
    """在一列文本里数若干个词的总出现次数。"""
    total = pd.Series(0, index=series.index, dtype="int64")
    for w in words:
        total = total + series.str.count(re.escape(w))
    return total


def add_imagery(df):
    """给每一首诗加上 10 个意象列，值 = 该意象在诗中出现次数。"""
    df = df.copy()
    src = df["正文繁"]                       # 用繁体原文统计，见文件头说明
    for name, words in IMAGERY.items():
        df[name] = _count_words(src, words)
    df["意象总数"] = df[list(IMAGERY)].sum(axis=1)
    return df


def add_season(df):
    """给每一首诗加上 4 个季节列。"""
    df = df.copy()
    src = df["正文繁"]
    for name, words in SEASON.items():
        df["季_" + name] = _count_words(src, words)
    return df


def build_features(df):
    df = add_imagery(df)
    df = add_season(df)
    return df
